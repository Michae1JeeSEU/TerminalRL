def _config(**overrides) -> SimConfig:
    values = {
        "arrival_model": "finite_cohort",
        "fixed_arrival_schedule": (0.0,),
        "total_requested_uavs": 1,
        "max_simulation_seconds": 100.0,
    }
    values.update(overrides)
    return SimConfig(**values)


def _rollout_signature(env: TerminalParallelEnv) -> dict:
    return {
        "time": env.now,
        # Plan UUIDs are intentionally generated by the canonical trajectory
        # generator.  Equivalence therefore compares the executed geometric
        # state, not independently-created UUID strings.
        "active": {uid: (uav.phase.value, tuple(uav.position), uav.energy_remaining,
                         None if uav.committed_plan is None else tuple(tuple(point.position) for point in uav.committed_plan.points))
                   for uid, uav in env.active.items()},
        "completed": [(uav.uid, uav.completion_time, uav.energy_remaining) for uav in env.completed_uavs],
        "outcomes": dict(env.ledger.outcomes),
        "telemetry": dict(env.telemetry),
        "conflicts": list(env.conflict_events),
    }


def test_env_runs_without_visualization_dependencies() -> None:
    env = TerminalParallelEnv(_config())
    observations, _ = env.reset(0)
    assert isinstance(observations, dict)


def test_step_observer_disabled_by_default() -> None:
    assert TerminalParallelEnv(_config())._step_observer is None


def test_step_observer_called_once_per_sim_tick() -> None:
    env = TerminalParallelEnv(_config())
    env.reset(0)
    observed: list[tuple[int, float]] = []
    env.set_step_observer(lambda world: observed.append((world.step_count, world.now)))
    env.step()
    assert observed == [(1, 1.0)]


def test_observer_does_not_change_step_api() -> None:
    env = TerminalParallelEnv(_config())
    env.reset(0)
    env.set_step_observer(lambda world: None)
    assert len(env.step()) == 5


def test_disabled_visualization_is_deterministic_equivalent() -> None:
    first = TerminalParallelEnv(_config())
    second = TerminalParallelEnv(_config())
    first.reset(7)
    second.reset(7)
    # A disabled renderer may consume snapshots, but it may not change any
    # authoritative state or rollout outcome.
    second.set_step_observer(lambda world: build_world_render_snapshot(world))
    for _ in range(40):
        first.step()
        second.step()
    assert _rollout_signature(second) == _rollout_signature(first)


def test_high_level_wrapper_emits_low_step_frames() -> None:
    config = _config(
        experiment_mode="dynamic_rule",
        high_level_enabled=True,
        high_level_decision_interval_seconds=3.0,
    )
    wrapper = DynamicHighLevelWrapper(config, RuleLowLevelAdapter())
    wrapper.reset(0)
    frames: list[int] = []
    wrapper.base.set_step_observer(lambda world: frames.append(world.step_count))
    wrapper.step(np.zeros(10, dtype=np.float32))
    assert frames == [1, 2, 3]


def test_uav_picker_uses_current_point_cloud_index() -> None:
    env = TerminalParallelEnv(_config())
    env.reset(0)
    env.step()
    snapshot = build_world_render_snapshot(env)
    assert Terminal3DViewer._uav_uid_from_point_id(snapshot, 0) == snapshot.uavs[0].uid
    assert Terminal3DViewer._uav_uid_from_point_id(snapshot, -1) is None
    assert Terminal3DViewer._uav_uid_from_point_id(snapshot, 1) is None


def test_viewer_observer_is_non_blocking_and_drops_stale_frames() -> None:
    class SlowViewer:
        def __init__(self):
            self.times = []

        def update(self, snapshot):
            time.sleep(0.03)
            self.times.append(snapshot.time)
            return True

    env = TerminalParallelEnv(_config(max_simulation_seconds=200.0))
    env.reset(0)
    viewer = SlowViewer()
    observer = ViewerStepObserver(viewer, VisualizationConfig(frame_stride=5))
    started = time.perf_counter()
    for index in range(100):
        env.step_count = index * 5
        env.now = float(index)
        observer(env)
    enqueue_wall = time.perf_counter() - started
    deadline = time.perf_counter() + 1.0
    while (not viewer.times or viewer.times[-1] != 99.0) and time.perf_counter() < deadline:
        time.sleep(0.01)
    observer.close()
    assert enqueue_wall < 0.15
    assert viewer.times[-1] == 99.0
    assert len(viewer.times) < 20
